#!/usr/bin/env bash
# Make PLAIN `cargo build` use a LOCAL xezim-core checkout instead of
# fetching the git dependency — persistently, by writing the repo-local
# (git-ignored) .cargo/local-core.toml with a [patch] section. The tracked
# .cargo/config.toml includes it and keeps the compiler defaults intact.
#
# Search order for the local checkout:
#   1. ./xezim-core   (nested checkout, e.g. the sv-tests vendored layout)
#   2. ../xezim-core  (sibling checkout, the usual co-develop layout)
#
# Usage:
#   ./scripts/use-local-core.sh            # enable (auto-detect)
#   ./scripts/use-local-core.sh /path/to/xezim-core
#   ./scripts/use-local-core.sh --remove   # back to the pinned git dep
#
# The patch overrides the git dependency (and any local Cargo.lock),
# so edits to the local core are picked up immediately. `cargo build` in a
# bare clone (no local checkout, no patch) resolves the EXACT core revision
# pinned by `rev =` in Cargo.toml — no accidental drift.
set -euo pipefail
cd "$(dirname "$(readlink -f "$0")")/.."

CFG=.cargo/local-core.toml

if [ "${1:-}" = "--remove" ]; then
  if [ -f "$CFG" ]; then rm -f "$CFG"; fi
  echo "local-core patch removed; cargo resolves the rev-pinned git dependency"
  exit 0
fi

if [ -n "${1:-}" ]; then
  CORE=$1
elif [ -f xezim-core/Cargo.toml ]; then
  CORE=./xezim-core
elif [ -f ../xezim-core/Cargo.toml ]; then
  CORE=../xezim-core
else
  echo "error: no xezim-core checkout found at ./xezim-core or ../xezim-core" >&2
  echo "       clone it, or pass the path: ./scripts/use-local-core.sh /path/to/xezim-core" >&2
  exit 1
fi
[ -f "$CORE/Cargo.toml" ] || { echo "error: $CORE does not look like a xezim-core checkout" >&2; exit 1; }

mkdir -p .cargo
cat > "$CFG" <<CFGEOF
# Generated by scripts/use-local-core.sh — NOT tracked by git.
# Makes plain \`cargo build\` use the local xezim-core checkout below
# instead of the rev-pinned git dependency. Remove with
# \`./scripts/use-local-core.sh --remove\`.
[patch."https://github.com/aionhw/xezim-core.git"]
xezim-core = { path = "$CORE" }
sv-parser = { path = "$CORE/xezim-parser" }
CFGEOF
echo "cargo will now build against $CORE (wrote $CFG)"
